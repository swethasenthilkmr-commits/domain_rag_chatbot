"""
Domain-Specific RAG Chatbot for PDF Question Answering
Module 7: Streamlit interface.

Run:  streamlit run app.py
"""

import os

import streamlit as st
from dotenv import load_dotenv

load_dotenv()   # load GOOGLE_API_KEY (and optional settings) before the other modules

from document_loader import validate_files, load_and_chunk, MAX_FILE_SIZE_MB, MAX_FILES
from vector_store import VectorStore, get_embedding_model
from rag_pipeline import answer_question, get_llm, TOP_K

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
SAMPLE_DIR = os.path.join(BASE_DIR, "documents")
INDEX_DIR = os.path.join(BASE_DIR, "vector_store", "saved_index")

st.set_page_config(page_title="RAG PDF Chatbot", page_icon="📚", layout="wide")


def get_api_key():
    """API key from .env (local) or Streamlit secrets (Streamlit Cloud). Never hard-coded."""
    key = os.getenv("GOOGLE_API_KEY")
    if not key:
        try:
            key = st.secrets["GOOGLE_API_KEY"]
        except Exception:
            key = None
    return key


@st.cache_resource(show_spinner="Loading the embedding model (first time can take a minute)...")
def load_embeddings():
    return get_embedding_model()


@st.cache_resource
def load_llm(api_key):
    return get_llm(api_key)


def process(files):
    """Validate, extract, chunk, embed and store the given (name, bytes) files."""
    errors = validate_files(files)
    if errors:
        for e in errors:
            st.sidebar.error(e)
        return
    with st.spinner("Reading PDFs, creating chunks and embeddings..."):
        chunks, report = load_and_chunk(files)
        st.session_state.report = report
        if not chunks:
            st.sidebar.error("No text could be extracted from these files.")
            return
        store = VectorStore.build(chunks, load_embeddings())
        store.save(INDEX_DIR)        # save locally so it can be reused
    st.session_state.store = store
    st.session_state.messages = []
    st.sidebar.success(f"Processed {len(files)} file(s) into {len(chunks)} chunks.")


# ---------------- session state ----------------
st.session_state.setdefault("store", None)
st.session_state.setdefault("messages", [])
st.session_state.setdefault("report", [])

# ---------------- sidebar ----------------
st.sidebar.header("📄 1. Documents")
uploaded = st.sidebar.file_uploader(
    f"Upload PDF files (max {MAX_FILES} files, {MAX_FILE_SIZE_MB} MB each)",
    type=["pdf"], accept_multiple_files=True)

if uploaded:
    st.sidebar.caption("Selected: " + ", ".join(f.name for f in uploaded))

if st.sidebar.button("⚙️ Process Documents", type="primary", use_container_width=True, disabled=not uploaded):
    process([(f.name, f.getvalue()) for f in uploaded])

sample_files = sorted(f for f in os.listdir(SAMPLE_DIR) if f.lower().endswith(".pdf")) if os.path.isdir(SAMPLE_DIR) else []
if sample_files and st.sidebar.button("📂 Use sample documents", use_container_width=True):
    process([(f, open(os.path.join(SAMPLE_DIR, f), "rb").read()) for f in sample_files])

if st.session_state.store is None and VectorStore.exists(INDEX_DIR):
    if st.sidebar.button("💾 Load last saved index", use_container_width=True):
        st.session_state.store = VectorStore.load(INDEX_DIR)
        st.sidebar.success("Saved index loaded.")

if st.session_state.store is not None:
    st.sidebar.markdown("**Active documents:**")
    for name in st.session_state.store.document_names():
        st.sidebar.write(f"• {name}")
    if st.sidebar.button("🗑️ Clear documents", use_container_width=True):
        st.session_state.store = None
        st.session_state.messages = []
        st.session_state.report = []
        st.rerun()

st.sidebar.header("💬 2. Chat")
top_k = st.sidebar.slider("Chunks to retrieve (top-k)", 3, 5, TOP_K)
if st.sidebar.button("🧹 Clear Chat", use_container_width=True):
    st.session_state.messages = []
    st.rerun()

st.sidebar.divider()
st.sidebar.caption("⚠️ Answers are generated by AI from the uploaded documents and may contain "
                   "mistakes. Verify important (high-stakes) information in the original document. "
                   "Do not upload confidential documents without permission.")

# ---------------- main area ----------------
st.title("📚 Domain-Specific RAG Chatbot")
st.write("Ask questions about your PDF documents. Answers are based **only** on the uploaded "
         "documents and show the source document and page.")

api_key = get_api_key()
if not api_key:
    st.error("GOOGLE_API_KEY not found. Add it to the .env file (local) or to the app's "
             "Secrets (Streamlit Cloud).")
    st.stop()

if st.session_state.store is None:
    st.info("👈 Upload PDF files and click **Process Documents**, or click **Use sample documents**.")
    with st.expander("How it works"):
        st.markdown(
            "1. Text is extracted from every PDF page (document name and page number are kept).\n"
            "2. The text is split into chunks of about 800 characters with 120 characters overlap.\n"
            "3. Each chunk is converted into an embedding with **all-MiniLM-L6-v2** and stored in **FAISS**.\n"
            "4. Your question is embedded and the most similar chunks are retrieved (cosine similarity).\n"
            "5. **Gemini** answers using only those chunks, and the sources are shown below the answer.")
    st.stop()

if st.session_state.report:
    with st.expander("📑 Processing summary"):
        st.table(st.session_state.report)


def show_sources(msg):
    if msg.get("sources"):
        with st.expander("📎 Sources"):
            for s in msg["sources"]:
                st.markdown(f"**{s['source']} – page {s['page']}** (similarity {s['score']})")
                st.caption(s["snippet"])
    elif msg.get("retrieved") is not None:
        st.caption("No supporting source was found in the uploaded documents.")


# chat history
for msg in st.session_state.messages:
    with st.chat_message(msg["role"]):
        st.markdown(msg["content"])
        if msg["role"] == "assistant":
            show_sources(msg)
            st.caption(f"⏱️ {msg.get('seconds', 0)} s")

# new question
question = st.chat_input("Ask a question about the documents...")
if question:
    question = question.strip()
    st.session_state.messages.append({"role": "user", "content": question})
    with st.chat_message("user"):
        st.markdown(question)

    with st.chat_message("assistant"):
        with st.spinner("Searching the documents..."):
            try:
                result = answer_question(question, st.session_state.store, load_embeddings(),
                                         load_llm(api_key), k=top_k)
                msg = {"role": "assistant", "content": result["answer"], "sources": result["sources"],
                       "retrieved": result["retrieved"], "seconds": result["seconds"]}
            except Exception as e:
                error = str(e)
                if "429" in error or "RESOURCE_EXHAUSTED" in error:
                    text = ("⚠️ The daily free limit for this Gemini model has been reached. "
                            "Please try again later, or set another model with LLM_MODEL in .env / Secrets.")
                elif "503" in error or "UNAVAILABLE" in error:
                    text = "⚠️ Gemini is busy right now (high demand). Please ask again in a minute."
                else:
                    text = f"⚠️ Could not get an answer from Gemini. Details: {error[:200]}"
                msg = {"role": "assistant", "seconds": 0, "content": text}
        st.markdown(msg["content"])
        show_sources(msg)
        st.caption(f"⏱️ {msg.get('seconds', 0)} s")
    st.session_state.messages.append(msg)
